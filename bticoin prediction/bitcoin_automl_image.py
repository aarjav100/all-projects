# ── 7.7 Grad-CAM visualisation (which pixels the CNN focuses on) ──
class GradCAM:
    def __init__(self, model, target_layer):
        self.model = model; self.grads = None; self.acts = None
        target_layer.register_forward_hook(lambda m,i,o: setattr(self,'acts',o))
        target_layer.register_backward_hook(lambda m,gi,go: setattr(self,'grads',go[0]))

    def __call__(self, x, class_idx=None):
        self.model.eval()
        out = self.model(x)
        if class_idx is None: class_idx = out.argmax(1).item()
        self.model.zero_grad()
        out[0, class_idx].backward()
        weights = self.grads.mean(dim=[2,3], keepdim=True)
        cam = (weights * self.acts).sum(1).squeeze()
        cam = torch.relu(cam).detach().cpu().numpy()
        cam = (cam - cam.min()) / (cam.max() - cam.min() + 1e-8)
        return cam, class_idx

