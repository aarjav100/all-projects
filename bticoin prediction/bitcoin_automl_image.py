def augment_image(img_bgr):
    pil = Image.fromarray(cv2.cvtColor(img_bgr, cv2.COLOR_BGR2RGB))
    results = {'Original': pil}
    results['Flip H']       = TF.hflip(pil)
    results['Flip V']       = TF.vflip(pil)
    results['Rotate +15']   = TF.rotate(pil, 15)
    results['Rotate -15']   = TF.rotate(pil, -15)
    results['Center crop']  = TF.center_crop(pil, [int(224*0.85), int(224*0.85)])
    results['Color jitter'] = T.ColorJitter(brightness=0.4, contrast=0.4, saturation=0.4)(pil)
    noise = np.array(pil).astype(np.float32)
    noise += np.random.randn(*noise.shape) * 15
    results['Gaussian noise'] = Image.fromarray(np.clip(noise,0,255).astype(np.uint8))
    return results

