def generate_combined_signal(close, rsi, sma20, predicted_close, cnn_pattern):
    pct = (predicted_close - close) / close * 100
    bullish_patterns = {'bull_flag','ascending_triangle','cup_handle'}
    bearish_patterns = {'head_shoulders','double_top'}
    tab_signal = 'BUY' if (close>sma20 and pct>0 and rsi<70) else 'SELL' if (rsi>70 or close<sma20*0.97) else 'HOLD'
    cnn_signal = 'BUY' if cnn_pattern in bullish_patterns else 'SELL' if cnn_pattern in bearish_patterns else 'HOLD'
    if tab_signal==cnn_signal: final='STRONG '+tab_signal
    elif tab_signal=='HOLD': final=cnn_signal
    elif cnn_signal=='HOLD': final=tab_signal
    else: final='CONFLICTING — review manually'
    return tab_signal, cnn_signal, final, pct

